function clave(nombre: string) {
  return nombre.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase();
}

const nombresPorClave = new Map(nombres.map((nombre) => [clave(nombre), nombre]));

export function nombreEnCarta(nombre: string): string {
  return nombresPorClave.get(clave(nombre)) ?? nombre;
}
